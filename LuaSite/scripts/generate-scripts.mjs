// Builds src/scripts.generated.ts from ../../Lua, so the page always lists the files in the repo.
import {readFile, readdir, writeFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const siteRoot = path.resolve(here, "..");
const luaDirectory = path.resolve(siteRoot, "../Lua");
const output = path.join(siteRoot, "src", "scripts.generated.ts");

const repository = "T2PeNBiX99wcoxKv3A4g/URLCheck";
const branch = "master";

/** The first `-- ...` line of a script is its one-line description. */
function describe(source) {
    for (const line of source.split(/\r?\n/)) {
        const match = /^--\s+(.+)$/.exec(line);
        if (match) return match[1].trim();
    }

    return "";
}

const names = (await readdir(luaDirectory)).filter((name) => name.endsWith(".lua")).sort();
const scripts = [];

for (const name of names) {
    const raw = `https://raw.githubusercontent.com/${repository}/${branch}/Lua/${name}`;

    scripts.push({
        name,
        description: describe(await readFile(path.join(luaDirectory, name), "utf8")),
        install: `urlcheck://script?url=${encodeURIComponent(raw)}`
    });
}

const file = `// Generated by scripts/generate-scripts.mjs from ../../Lua; do not edit.
export interface ScriptEntry {
    name: string;
    description: string;
    install: string;
}

export const scripts: ScriptEntry[] = ${JSON.stringify(scripts, null, 4)};
`;

await writeFile(output, file, "utf8");
console.log(`Generated ${scripts.length} scripts into ${path.relative(siteRoot, output)}`);
