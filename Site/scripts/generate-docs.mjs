// Builds src/docs.generated.ts from the project wiki, in every language the app supports.
//
// The wiki is a separate repository. A local clone in ../Wiki (or the folder named by WIKI_DIR) is
// used when it exists, so the site can be built offline and before the wiki is pushed; otherwise the
// pages are fetched from the wiki's raw URLs. A missing translation falls back to English.
import {existsSync} from "node:fs";
import {readFile, writeFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const siteRoot = path.resolve(here, "..");
const output = path.join(siteRoot, "src", "docs.generated.ts");
const localWiki = process.env.WIKI_DIR ?? (existsSync(path.join(siteRoot, "..", "Wiki")) ? path.join(siteRoot, "..", "Wiki") : null);

const repository = "T2PeNBiX99wcoxKv3A4g/URLCheck";

/** English is the source; the others are the `<page>.<language>.md` files beside it. */
const languages = ["en", "ja", "zh-CN", "zh-TW"];

const pages = [
    {slug: "Lua-Scripts", group: "scripting"},
    {slug: "Lua-Script-Examples", group: "scripting"},
    {slug: "API", group: "scripting"},
    {slug: "_G", group: "libraries"},
    {slug: "table", group: "libraries"},
    {slug: "string", group: "libraries"},
    {slug: "math", group: "libraries"},
    {slug: "coroutine", group: "libraries"},
    {slug: "bit32", group: "libraries"}
];

const known = new Set(pages.map((page) => page.slug));

/** Wiki links point at page names; on the site they become hash routes. A translated page links to
 * `Lua-Scripts.ja` in the wiki, which is the same page on the site. */
function rewriteLinks(body) {
    return body.replace(/\]\(([^)\s]+)\)/g, (match, target) => {
        const page = target.split("#")[0].replace(/\.(?:ja|zh-CN|zh-TW)$/, "");
        return known.has(page) ? `](#/docs/${page})` : match;
    });
}

/** The page title is its first heading, which is translated along with the rest of the text. */
function titleOf(body, fallback) {
    const match = /^#\s+(.+)$/m.exec(body);
    return match ? match[1].trim() : fallback;
}

async function read(slug, language) {
    const name = language === "en" ? slug : `${slug}.${language}`;

    if (localWiki) {
        const translated = path.join(localWiki, `${name}.md`);
        if (existsSync(translated)) return await readFile(translated, "utf8");

        return await readFile(path.join(localWiki, `${slug}.md`), "utf8");
    }

    const response = await fetch(`https://raw.githubusercontent.com/wiki/${repository}/${name}.md`);
    if (response.ok) return await response.text();

    const fallback = await fetch(`https://raw.githubusercontent.com/wiki/${repository}/${slug}.md`);
    if (!fallback.ok) throw new Error(`Cannot read the wiki page ${slug}: HTTP ${fallback.status}`);

    return await fallback.text();
}

const docs = {};

for (const language of languages) {
    docs[language] = [];

    for (const page of pages) {
        const body = rewriteLinks(await read(page.slug, language));
        docs[language].push({...page, title: titleOf(body, page.slug), body});
    }
}

const file = `// Generated by scripts/generate-docs.mjs from the project wiki; do not edit.
export type DocGroup = "scripting" | "libraries";

export interface DocPage {
    slug: string;
    group: DocGroup;
    title: string;
    body: string;
}

export const docs: Record<string, DocPage[]> = ${JSON.stringify(docs, null, 4)};
`;

await writeFile(output, file, "utf8");
console.log(`Generated ${pages.length} wiki pages in ${languages.length} languages into ${path.relative(siteRoot, output)}`);
