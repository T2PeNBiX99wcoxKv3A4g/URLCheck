// Builds src/docs.generated.ts from the project wiki, so the site always mirrors it.
//
// The wiki is a separate repository. A local clone in ../Wiki (or the folder named by WIKI_DIR) is
// used when it exists, so the site can be built offline and before the wiki is pushed; otherwise the
// pages are fetched from the wiki's raw URLs.
import {existsSync} from "node:fs";
import {readFile, writeFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const siteRoot = path.resolve(here, "..");
const output = path.join(siteRoot, "src", "docs.generated.ts");
const localWiki = process.env.WIKI_DIR ?? (existsSync(path.join(siteRoot, "..", "Wiki")) ? path.join(siteRoot, "..", "Wiki") : null);

const repository = "T2PeNBiX99wcoxKv3A4g/URLCheck";

const pages = [
    {slug: "Lua-Scripts", title: "Lua scripts", group: "Scripting"},
    {slug: "Lua-Script-Examples", title: "Examples", group: "Scripting"},
    {slug: "API", title: "API reference", group: "Scripting"},
    {slug: "_G", title: "_G", group: "Libraries"},
    {slug: "table", title: "table", group: "Libraries"},
    {slug: "string", title: "string", group: "Libraries"},
    {slug: "math", title: "math", group: "Libraries"},
    {slug: "coroutine", title: "coroutine", group: "Libraries"},
    {slug: "bit32", title: "bit32", group: "Libraries"}
];

const known = new Set(pages.map((page) => page.slug));

/** Wiki links point at page names; on the site they become hash routes. */
function rewriteLinks(body) {
    return body.replace(/\]\(([^)\s]+)\)/g, (match, target) => {
        const page = target.split("#")[0];
        return known.has(page) ? `](#/docs/${page})` : match;
    });
}

async function read(page) {
    if (localWiki) return await readFile(path.join(localWiki, `${page.slug}.md`), "utf8");

    const response = await fetch(`https://raw.githubusercontent.com/wiki/${repository}/${page.slug}.md`);
    if (!response.ok) throw new Error(`Cannot read the wiki page ${page.slug}: HTTP ${response.status}`);

    return await response.text();
}

const docs = [];

for (const page of pages) {
    docs.push({...page, body: rewriteLinks(await read(page))});
}

const file = `// Generated by scripts/generate-docs.mjs from the project wiki; do not edit.
export interface DocPage {
    slug: string;
    title: string;
    group: string;
    body: string;
}

export const docs: DocPage[] = ${JSON.stringify(docs, null, 4)};
`;

await writeFile(output, file, "utf8");
console.log(`Generated ${docs.length} wiki pages into ${path.relative(siteRoot, output)}`);
