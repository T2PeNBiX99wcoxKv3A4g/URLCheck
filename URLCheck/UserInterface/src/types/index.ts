export interface HistoryItem {
    id: number;
    url: string;
    /** Unix epoch milliseconds (UTC). */
    timestamp: number;
}

export interface AppSettings {
    requestTimeoutMs: number;
    userAgents: UserAgentEntry[];
    /** Id of the entry used for outbound requests; falls back to the first entry. */
    selectedUserAgentId: string;
    browsers: BrowserEntry[];
    language: string;
    /** Cross-platform: show the popup without window decorations, drawing our own rounded frame. */
    borderlessPopup: boolean;
    /** Strip known tracking parameters from a URL as soon as the popup opens. */
    autoStripTrackingParams: boolean;
    /** Start with the management window hidden, like a link launch. Ignored without a tray icon. */
    hideOnLaunch: boolean;
    /** Watch the clipboard and float a button over the pointer whenever a copied text is an http(s) URL. */
    showUrlButton: boolean;
    /** Display name this device advertises to peers. */
    deviceName: string;
    /** Stable identifier for this device, generated by the backend. */
    deviceId: string;
    /** Shared secret for device forwarding; the listener only runs while it is set. */
    pairingCode: string;
    /** Port this device listens on for incoming forwarded URLs. */
    forwardPort: number;
    /** Peer devices URLs can be forwarded to; the popup hides its button while this is empty. */
    devices: DeviceEntry[];
}

export interface DeviceEntry {
    id: string;
    name: string;
    /** Host name or IP address of the peer on the local network. */
    host: string;
    /** Port the peer's forwarding listener is bound to. */
    port: number;
}

export interface UserAgentEntry {
    id: string;
    name: string;
    value: string;
}

export interface BrowserEntry {
    id: string;
    name: string;
    executablePath: string;
    arguments: string;
    useCount: number;
}
