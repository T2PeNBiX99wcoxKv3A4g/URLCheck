export interface HistoryItem {
    id: number;
    url: string;
    /** Unix epoch milliseconds (UTC). */
    timestamp: number;
}

export interface AppSettings {
    requestTimeoutMs: number;
    userAgents: UserAgentEntry[];
    /** Id of the entry used for outbound requests; falls back to the first entry. */
    selectedUserAgentId: string;
    browsers: BrowserEntry[];
    language: string;
    /** Cross-platform: show the popup without window decorations, drawing our own rounded frame. */
    borderlessPopup: boolean;
    /** Strip known tracking parameters from a URL as soon as the popup opens. */
    autoStripTrackingParams: boolean;
    /** Hosts whose links are followed through their redirects before the popup opens. */
    autoRedirectHosts: string[];
    /** Start with the management window hidden, like a link launch. Ignored without a tray icon. */
    hideOnLaunch: boolean;
    /** Watch the clipboard and float a button over the pointer whenever a copied text is an http(s) URL. */
    showUrlButton: boolean;
    /** Accept pairing requests and forwarded URLs: opens the listener and answers discovery queries. */
    forwardingEnabled: boolean;
    /** Display name this device advertises to peers. */
    deviceName: string;
    /** Stable identifier for this device, generated by the backend. */
    deviceId: string;
    /** Port this device listens on for pairing and incoming forwarded URLs. */
    forwardPort: number;
    /** Check the installed filter lists on startup and keep refreshing them while the app runs. */
    filterAutoUpdate: boolean;
    /** Hours between automatic filter list refreshes; -1 turns the timer off (startup check only). */
    filterAutoUpdateHours: number;
    /** Paired devices URLs can be forwarded to; the popup hides its button while this is empty. */
    devices: DeviceEntry[];
}

export interface DeviceEntry {
    id: string;
    name: string;
    /** Host name or IP address of the peer on the local network. */
    host: string;
    /** Port the peer's listener is bound to. */
    port: number;
    /** The peer's Ed25519 public key, base64. Empty until the device has been paired. */
    publicKey: string;
    /**
     * Extra addresses (host names or IPs) tried when the primary `host` cannot be reached, e.g. a
     * private `.lan` name that survives an address change. All share `port`.
     */
    addresses: string[];
}

export interface UserAgentEntry {
    id: string;
    name: string;
    value: string;
}

export interface BrowserEntry {
    id: string;
    name: string;
    executablePath: string;
    arguments: string;
    useCount: number;
}
