#!/usr/bin/env bash
#
# Builds the Arch Linux package from a published linux-x64 build.
#
# Run it on Arch, or in the container the release workflow uses:
#   docker run --rm -v "$PWD:/src" -w /src -e VERSION=0.10.4 archlinux:latest \
#     bash -c "pacman -Sy --noconfirm --needed zstd libarchive && installer/linux/build-arch.sh"
#
# The version, publish directory and output directory come from the environment, so the same script
# works locally and in CI.
set -euo pipefail

version="${VERSION:?VERSION must be set, e.g. 0.10.4}"
publish_dir="${PUBLISH_DIR:-publish/linux-x64}"
output_dir="${OUTPUT_DIR:-release}"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"

# Paths may be absolute (a local run) or relative to the repository (what CI passes).
[[ "$publish_dir" = /* ]] || publish_dir="$repo/$publish_dir"
[[ "$output_dir" = /* ]] || output_dir="$repo/$output_dir"

if [[ ! -f "$publish_dir/URLCheck" ]]; then
    echo "No URLCheck in $publish_dir; publish for linux-x64 first." >&2
    exit 1
fi

stage="$(mktemp -d)"
trap 'rm -rf "$stage"' EXIT

install -Dpm 0755 "$publish_dir/URLCheck" "$stage/opt/URLCheck/URLCheck"
install -Dpm 0644 "$here/urlcheck.desktop" "$stage/usr/share/applications/urlcheck.desktop"
install -Dpm 0644 "$here/urlcheck.png" "$stage/usr/share/icons/hicolor/256x256/apps/urlcheck.png"

mkdir -p "$stage/usr/bin"
ln -s /opt/URLCheck/URLCheck "$stage/usr/bin/urlcheck"

# pacman reads the metadata from .PKGINFO; the size is informational.
cat > "$stage/.PKGINFO" <<EOF
# Generated by installer/linux/build-arch.sh
pkgname = urlcheck
pkgbase = urlcheck
pkgver = $version-1
pkgdesc = Link intermediary that inspects and cleans a URL before opening it
url = https://github.com/T2PeNBiX99wcoxKv3A4g/URLCheck
builddate = $(date +%s)
packager = yukiyosanako <yukiyosanako@users.noreply.github.com>
size = $(du -sb "$stage" | cut -f1)
arch = x86_64
license = MIT
depend = gtk3
depend = webkit2gtk-4.1
depend = libnotify
depend = icu
depend = openssl
depend = zlib
depend = krb5
depend = fontconfig
depend = freetype2
EOF

# makepkg writes a gzipped mtree file next to the package info, so do the same.
(
    cd "$stage"
    bsdtar -czf .MTREE --format=mtree \
        --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' \
        .PKGINFO opt usr
)

mkdir -p "$output_dir"
(
    cd "$stage"
    bsdtar -cf - .PKGINFO .MTREE opt usr
) | zstd -19 -q -c > "$output_dir/urlcheck-${version}-1-x86_64.pkg.tar.zst"

ls -l "$output_dir"/*.pkg.tar.zst
